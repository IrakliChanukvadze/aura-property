export type EditorCopyKey = keyof typeof copy;
export type ContentLocale = "en" | "ka" | "ru" | "he";

export function editorCopy(key: EditorCopyKey): string {
  const language = localStorage.getItem("aura-admin-locale") || "en";
  const index = { ka: 0, ru: 1, he: 2 }[language as "ka" | "ru" | "he"];
  return index === undefined ? key : copy[key][index];
}

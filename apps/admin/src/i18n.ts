export function t(text: string) {
  const locale = localStorage.getItem("aura-admin-locale") || "en";
  const entry =
    translations[text] ||
    Object.values(translations).find((value) =>
      Object.values(value).includes(text),
    );
  return (
    entry?.[locale] ||
    (locale === "en" && entry
      ? Object.keys(translations).find((key) => translations[key] === entry) ||
        text
      : text)
  );
}
